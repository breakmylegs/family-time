// Reads topics/*.md and sources.yaml, runs the checks, and writes dist/content.js with its types.
// Run by the package's build after tsc, through cli.ts. Any error fails the build; warnings are printed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkContent } from './check.js';
import { ContentError, parseSources, parseTopic } from './parse.js';
import type { Topic } from './types.js';

export function loadContent(root: string) {
  const dir = join(root, 'topics');
  const files = new Map<string, string>();
  const topics: Topic[] = [];
  for (const name of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
    const topic = parseTopic(name, readFileSync(join(dir, name), 'utf8'));
    files.set(topic.id, name);
    topics.push(topic);
  }
  const sources = parseSources('sources.yaml', readFileSync(join(root, 'sources.yaml'), 'utf8'));
  return { topics, sources, files };
}

export function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  let loaded;
  try {
    loaded = loadContent(root);
  } catch (err) {
    if (err instanceof ContentError) {
      console.error(`help-content: ${err.message}`);
      process.exit(1);
    }
    throw err;
  }
  const { topics, sources, files } = loaded;
  const { errors, warnings } = checkContent(topics, sources, new Date(), files);
  for (const w of warnings) console.warn(`help-content: warning: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`help-content: ${e}`);
    process.exit(1);
  }
  const content = { topics: Object.fromEntries(topics.map((t) => [t.id, t])), sources: Object.fromEntries(sources.map((s) => [s.id, s])) };
  const ids = topics.map((t) => `'${t.id}'`).join(' | ');
  writeFileSync(join(root, 'dist', 'content.js'), `// Generated by src/build.ts from topics/ and sources.yaml. Do not edit.\nexport default ${JSON.stringify(content, null, 2)};\n`);
  writeFileSync(
    join(root, 'dist', 'content.d.ts'),
    `// Generated by src/build.ts. Do not edit.\nimport type { Content } from './types.js';\nexport type TopicId = ${ids};\ndeclare const content: Content<TopicId>;\nexport default content;\n`,
  );
  console.log(`help-content: ${topics.length} topics, ${sources.length} sources`);
}
